/**
 * Downloadable research reports from the AI Research Assistant: a single
 * answer ("Export PDF" / "Export DOCX" under a response) or a whole
 * conversation ("Export conversation").
 *
 * Both formats are built from the same block model:
 * - a masthead with the journal's name, ISSN and publisher, the report
 *   title, and when and how it was generated;
 * - each question and its answer, with the answer's Markdown (headings,
 *   lists, tables, emphasis) laid out properly and numbered citations;
 * - the evidence behind each answer (the cited passages);
 * - a consolidated APA reference list built from the journal's own
 *   verified metadata, never from what the browser sent;
 * - a note on how the report was produced and how to use it.
 *
 * PDF: PDFKit with standard fonts in the house purple-and-gold palette
 * (same family as the guides and certificates). DOCX: the `docx` package,
 * fully editable, with real Word headings, lists and tables.
 */
