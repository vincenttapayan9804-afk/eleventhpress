const PURPLE = "#4c1d95";
const PURPLE_DEEP = "#2a1458";
const GOLD = "#c9a55c";
const GOLD_DEEP = "#8a6a28";
const INK = "#241b3a";
const BODY = "#2e2742";
const MUTED = "#6b6478";
const RULE = "#e4dfee";
const TINT = "#f7f4fc";
const AMBER_TINT = "#fdf6e7";
const GREEN = "#1f6f4a";

const PAGE_W = 595.28;
const PAGE_H = 841.89;
const M = 56;
const CW = PAGE_W - 2 * M;
const TOP = 72;
const BOTTOM_LIMIT = PAGE_H - 70;

export async function buildResearchPdf(report: ResearchReport): Promise<Buffer> {
  // Whitelabel: the tenant's colours replace the purple/gold palette.
  const { purple: PURPLE, purpleDeep: PURPLE_DEEP, gold: GOLD, goldDeep: GOLD_DEEP } = paletteFor(report.journal);
  const credit = report.journal.whitelabel ? POWERED_BY_CREDIT : null;
  return new Promise<Buffer>((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margins: { top: TOP, bottom: 70, left: M, right: M },
      bufferPages: true,
      info: {
        Title: pdfSafe(report.title),
        Author: pdfSafe(`${report.journal.name} — AI Research Assistant`),
        Subject: pdfSafe(report.items[0]?.question ?? report.title),
        Creator: pdfSafe(report.journal.name),
      },
    });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const t = (s: string) => pdfSafe(s);
    const ensure = (h: number) => {
      if (doc.y + h > BOTTOM_LIMIT) {
        doc.addPage();
        doc.x = M;
        doc.y = TOP;
      }
    };
    const label = (text: string, color = PURPLE, keepWithNext = 24) => {
      ensure(keepWithNext);
      doc.font("Helvetica-Bold").fontSize(7).fillColor(color).text(t(text.toUpperCase()), M, doc.y, { characterSpacing: 1.4, width: CW });
      doc.moveDown(0.35);
    };

    // Inline runs with bold/italic/links; citation markers in purple.
    const runs = (items: Inline[], size: number, color: string, opts: { indent?: number; width?: number; serif?: boolean } = {}) => {
      const x = M + (opts.indent ?? 0);
      const width = opts.width ?? CW - (opts.indent ?? 0);
      const pieces: (Inline & { cite?: boolean })[] = [];
      for (const it of items) {
        const parts = it.text.split(/(\[\d+\])/);
        for (const p of parts) if (p) pieces.push({ ...it, text: p, cite: /^\[\d+\]$/.test(p) });
      }
      if (pieces.length === 0) return;
      const serif = opts.serif ?? true;
      pieces.forEach((p, i) => {
        const font = p.code
          ? "Courier"
          : serif
            ? p.bold && p.italic
              ? "Times-BoldItalic"
              : p.bold
                ? "Times-Bold"
                : p.italic
                  ? "Times-Italic"
                  : "Times-Roman"
            : p.bold
              ? "Helvetica-Bold"
              : p.italic
                ? "Helvetica-Oblique"
                : "Helvetica";
        doc
          .font(p.cite ? "Helvetica-Bold" : font)
          .fontSize(p.cite ? size - 2.2 : size)
          .fillColor(p.cite ? PURPLE : p.link ? PURPLE : color);
        const textOpts: PDFKit.Mixins.TextOptions = { continued: i < pieces.length - 1, lineGap: 2.2, width, ...(p.link ? { link: p.link, underline: false } : {}) };
        if (i === 0) doc.text(t(p.text), x, doc.y, textOpts);
        else doc.text(t(p.text), textOpts);
      });
      doc.x = M;
    };

    const table = (header: string[], rows: string[][]) => {
      const cols = Math.max(header.length, ...rows.map((r) => r.length));
      if (cols === 0) return;
      const colW = CW / cols;
      const pad = 4;
      const drawRow = (cells: string[], isHeader: boolean) => {
        doc.font(isHeader ? "Helvetica-Bold" : "Helvetica").fontSize(isHeader ? 7.4 : 7.8);
        const heights = Array.from({ length: cols }, (_, c) => doc.heightOfString(t(cells[c] ?? ""), { width: colW - pad * 2, lineGap: 1 }));
        const h = Math.max(...heights) + pad * 2;
        if (doc.y + h > BOTTOM_LIMIT) {
          doc.addPage();
          doc.y = TOP;
        }
        const y = doc.y;
        if (isHeader) doc.rect(M, y, CW, h).fill(PURPLE_DEEP);
        else doc.rect(M, y, CW, h).fill("#ffffff");
        doc.lineWidth(0.5).strokeColor(RULE);
        for (let c = 0; c < cols; c++) {
          doc.rect(M + c * colW, y, colW, h).stroke();
          doc
            .font(isHeader ? "Helvetica-Bold" : "Helvetica")
            .fontSize(isHeader ? 7.4 : 7.8)
            .fillColor(isHeader ? "#ffffff" : BODY)
            .text(t(cells[c] ?? ""), M + c * colW + pad, y + pad, { width: colW - pad * 2, lineGap: 1 });
        }
        doc.y = y + h;
      };
      ensure(40);
      drawRow(header, true);
      for (const r of rows) drawRow(r, false);
      doc.x = M;
      doc.moveDown(0.6);
    };

    const renderBlocks = (blocks: Block[]) => {
      for (const b of blocks) {
        switch (b.type) {
          case "heading":
            ensure(40);
            doc.moveDown(0.3);
            doc.font("Times-Bold").fontSize(b.level <= 2 ? 13 : 11.6).fillColor(PURPLE).text(t(b.inlines.map((i) => i.text).join("")), M, doc.y, { width: CW });
            doc.moveTo(M, doc.y + 2).lineTo(M + 36, doc.y + 2).lineWidth(1).strokeColor(GOLD).stroke();
            doc.moveDown(0.5);
            break;
          case "paragraph":
            ensure(30);
            runs(b.inlines, 10.4, BODY);
            doc.moveDown(0.55);
            break;
          case "list":
            b.items.forEach((item, i) => {
              ensure(24);
              const y = doc.y;
              doc.font("Helvetica-Bold").fontSize(8.6).fillColor(GOLD_DEEP).text(b.ordered ? `${i + 1}.` : "•", M + 4, y + 1, { width: 14, lineBreak: false });
              doc.y = y;
              runs(item, 10.2, BODY, { indent: 18 });
              doc.moveDown(0.25);
            });
            doc.moveDown(0.35);
            break;
          case "table":
            table(b.header, b.rows);
            break;
          case "quote": {
            ensure(30);
            const y = doc.y;
            runs(b.inlines, 10, MUTED, { indent: 14 });
            doc.moveTo(M + 4, y).lineTo(M + 4, doc.y).lineWidth(2).strokeColor(GOLD).stroke();
            doc.moveDown(0.5);
            break;
          }
          case "code":
            ensure(30);
            doc.font("Courier").fontSize(8.6).fillColor(INK).text(t(b.text), M + 8, doc.y, { width: CW - 16 });
            doc.moveDown(0.5);
            break;
          case "rule":
            ensure(12);
            doc.moveTo(M, doc.y).lineTo(M + CW, doc.y).lineWidth(0.5).strokeColor(RULE).stroke();
            doc.moveDown(0.6);
            break;
        }
      }
    };

    // ---- Masthead ----
    const bandH = 188;
    doc.rect(0, 0, PAGE_W, bandH).fill(PURPLE_DEEP);
    doc.rect(0, bandH, PAGE_W, 3).fill(GOLD);
    doc.font("Helvetica-Bold").fontSize(7.6).fillColor(GOLD).text(t(report.journal.name.toUpperCase()), M, 40, { characterSpacing: 2, width: CW, lineBreak: false });
    const meta = [report.journal.issn ? `ISSN ${report.journal.issn}` : null, report.journal.eissn ? `e-ISSN ${report.journal.eissn}` : null, report.journal.publisher !== report.journal.name ? report.journal.publisher : null].filter(Boolean).join("  ·  ");
    if (meta) doc.font("Helvetica").fontSize(8).fillColor("#d9cff0").text(t(meta), M, 54, { width: CW, lineBreak: false });
    doc.font("Helvetica-Bold").fontSize(7.2).fillColor(GOLD).text(report.scope === "conversation" ? "AI RESEARCH ASSISTANT  ·  CONVERSATION REPORT" : "AI RESEARCH ASSISTANT  ·  RESEARCH BRIEF", M, 84, { characterSpacing: 1.6, width: CW, lineBreak: false });
    doc.font("Times-Bold").fontSize(21).fillColor("#ffffff").text(t(report.title), M, 100, { width: CW, lineGap: 1, height: 58, ellipsis: true });
    doc
      .font("Helvetica")
      .fontSize(8)
      .fillColor("#e4dcf5")
      .text(t(`Generated ${longDate(report.generatedAt)}  ·  ${report.items.length} question${report.items.length === 1 ? "" : "s"}  ·  ${report.siteUrl.replace(/^https?:\/\//, "")}`), M, bandH - 24, { width: CW, lineBreak: false });

    doc.y = bandH + 22;
    doc.x = M;

    // ---- About this report ----
    const noteH = doc.font("Helvetica").fontSize(8.2).heightOfString(t(REPORT_NOTE), { width: CW - 24, lineGap: 1.5 }) + 30;
    doc.rect(M, doc.y, CW, noteH).fill(TINT);
    doc.rect(M, doc.y, 3, noteH).fill(GOLD);
    const ny = doc.y;
    doc.font("Helvetica-Bold").fontSize(6.8).fillColor(PURPLE).text("ABOUT THIS REPORT", M + 14, ny + 9, { characterSpacing: 1.4, lineBreak: false });
    doc.font("Helvetica").fontSize(8.2).fillColor(BODY).text(t(REPORT_NOTE), M + 14, ny + 20, { width: CW - 24, lineGap: 1.5 });
    doc.y = ny + noteH + 18;
    doc.x = M;

    // ---- Questions and answers ----
    report.items.forEach((item, idx) => {
      ensure(90);
      label(report.items.length > 1 ? `Question ${idx + 1}` : "Question");
      const qh = doc.font("Times-Italic").fontSize(12).heightOfString(t(item.question), { width: CW - 24, lineGap: 1.5 }) + 16;
      const qy = doc.y;
      doc.rect(M, qy, CW, qh).fill(TINT);
      doc.rect(M, qy, 3, qh).fill(PURPLE);
      doc.font("Times-Italic").fontSize(12).fillColor(INK).text(t(item.question), M + 14, qy + 8, { width: CW - 24, lineGap: 1.5 });
      doc.y = qy + qh + 14;
      doc.x = M;

      label("Answer", PURPLE, 60);
      renderBlocks(markdownBlocks(item.answer));

      if (item.evidenceStatus) {
        ensure(30);
        const msg = STATUS_LABEL[item.evidenceStatus];
        const color = item.evidenceStatus === "verified" ? GREEN : GOLD_DEEP;
        const notes = [msg, ...(item.warnings ?? [])].join("\n");
        const h = doc.font("Helvetica").fontSize(7.8).heightOfString(t(notes), { width: CW - 20, lineGap: 1 }) + 12;
        const y = doc.y;
        doc.rect(M, y, CW, h).fill(item.evidenceStatus === "verified" ? "#eef7f1" : AMBER_TINT);
        doc.font("Helvetica-Bold").fontSize(7.8).fillColor(color).text(t(msg), M + 10, y + 6, { width: CW - 20 });
        if (item.warnings?.length) doc.font("Helvetica").fontSize(7.8).fillColor(BODY).text(t(item.warnings.join("\n")), M + 10, doc.y, { width: CW - 20, lineGap: 1 });
        doc.y = y + h + 12;
        doc.x = M;
      }

      if (item.citations.length) {
        label("Evidence cited", GOLD_DEEP, 80);
        for (const c of item.citations) {
          const s = item.sources.find((x) => x.id === c.sourceId);
          const excerpt = c.text.replace(/\s+/g, " ").trim();
          const body = `${c.kind === "record" ? "Article record: " : ""}“${excerpt.length > 420 ? `${excerpt.slice(0, 420)}…` : excerpt}”`;
          const h = doc.font("Times-Roman").fontSize(8.8).heightOfString(t(body), { width: CW - 30 }) + (s ? 14 : 4);
          ensure(h + 6);
          const y = doc.y;
          doc.font("Helvetica-Bold").fontSize(8).fillColor(PURPLE).text(`[${c.n}]`, M, y + 1, { width: 26, lineBreak: false });
          if (s) {
            doc.font("Helvetica-Bold").fontSize(8.2).fillColor(INK).text(t(s.title), M + 28, y, { width: CW - 30, link: s.url, lineBreak: true });
          }
          doc.font("Times-Roman").fontSize(8.8).fillColor(MUTED).text(t(body), M + 28, doc.y + 1, { width: CW - 30, lineGap: 0.8 });
          doc.moveDown(0.45);
          doc.x = M;
        }
      }
      if (idx < report.items.length - 1) {
        ensure(20);
        doc.moveDown(0.6);
        doc.moveTo(M, doc.y).lineTo(M + CW, doc.y).lineWidth(0.6).strokeColor(RULE).stroke();
        doc.moveDown(1);
      }
    });

    // ---- References ----
    const refs = consolidatedReferences(report);
    if (refs.length) {
      ensure(70);
      doc.moveDown(0.8);
      doc.font("Times-Bold").fontSize(14).fillColor(PURPLE).text("References", M, doc.y, { width: CW });
      doc.moveTo(M, doc.y + 2).lineTo(M + 36, doc.y + 2).lineWidth(1).strokeColor(GOLD).stroke();
      doc.moveDown(0.7);
      for (const r of refs) {
        const h = doc.font("Times-Roman").fontSize(9.6).heightOfString(t(r.reference), { width: CW - 18, indent: -18 }) + 6;
        ensure(h);
        doc.font("Times-Roman").fontSize(9.6).fillColor(BODY).text(t(r.reference), M + 18, doc.y, { width: CW - 18, indent: -18, lineGap: 1.2, link: r.url });
        doc.moveDown(0.45);
      }
    }

    // ---- Running header and footer on every page ----
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      // Writing in the margins must not trigger PDFKit's automatic page break.
      doc.page.margins.bottom = 0;
      doc.page.margins.top = 0;
      const pageNo = i - range.start + 1;
      if (pageNo > 1) {
        doc.font("Helvetica-Bold").fontSize(6.6).fillColor(GOLD_DEEP).text(t(report.journal.name.toUpperCase()), M, 36, { characterSpacing: 1.4, width: CW / 2, lineBreak: false });
        doc.font("Helvetica").fontSize(6.8).fillColor(MUTED).text("AI Research Assistant", M + CW / 2, 36, { width: CW / 2, align: "right", lineBreak: false });
        doc.moveTo(M, 50).lineTo(M + CW, 50).lineWidth(0.4).strokeColor(RULE).stroke();
      }
      doc.moveTo(M, PAGE_H - 50).lineTo(M + CW, PAGE_H - 50).lineWidth(0.4).strokeColor(RULE).stroke();
      doc.font("Helvetica").fontSize(6.8).fillColor(MUTED).text("AI-generated from the journal's published articles. Verify against the original publications.", M, PAGE_H - 42, { width: CW - 70, lineBreak: false });
      doc.font("Helvetica-Bold").fontSize(6.8).fillColor(PURPLE).text(`${pageNo} / ${range.count}`, M + CW - 60, PAGE_H - 42, { width: 60, align: "right", lineBreak: false });
      if (credit) doc.font("Helvetica").fontSize(6.2).fillColor(MUTED).text(credit, M, PAGE_H - 31, { width: CW, align: "center", lineBreak: false });
    }
    doc.end();
  });
}

