// ---------------------------------------------------------------------------
// Report model
// ---------------------------------------------------------------------------

export interface ReportSource {
  id: string;
  title: string;
  reference: string;
  url: string;
}

export interface ReportCitation {
  n: number;
  /** The source this citation points at, by id. */
  sourceId: string;
  kind: "passage" | "record";
  text: string;
}

export interface ReportItem {
  question: string;
  answer: string;
  citations: ReportCitation[];
  /** Sources cited in this answer, in citation order. */
  sources: ReportSource[];
  evidenceStatus?: "verified" | "review" | "unsupported";
  warnings?: string[];
  answeredAt?: string | null;
}

export interface ResearchReport {
  title: string;
  scope: "response" | "conversation";
  items: ReportItem[];
  journal: JournalInfo;
  generatedAt: Date;
  siteUrl: string;
}

const STATUS_LABEL: Record<NonNullable<ReportItem["evidenceStatus"]>, string> = {
  verified: "Evidence check passed: every citation points to the journal's own records.",
  review: "Evidence check: some details need review (see notes).",
  unsupported: "Evidence check: the journal's records do not answer this question.",
};

export const REPORT_NOTE =
  "This report was generated by the journal's AI Research Assistant, which answers only from the journal's published articles. Numbers in square brackets refer to the evidence listed after each answer; references were built from the journal's verified publication metadata. AI-generated text can still contain errors: check important details against the original articles before relying on or citing them.";

/** Every source cited anywhere in the report, de-duplicated, sorted for an APA list. */
export function consolidatedReferences(report: ResearchReport): ReportSource[] {
  const byId = new Map<string, ReportSource>();
  for (const item of report.items) for (const s of item.sources) if (!byId.has(s.id)) byId.set(s.id, s);
  return [...byId.values()].sort((a, b) => a.reference.localeCompare(b.reference));
}

export function reportFileName(report: ResearchReport, ext: "pdf" | "docx" | "md"): string {
  const slug = report.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60) || "research-brief";
  const date = report.generatedAt.toISOString().slice(0, 10);
  return `research-assistant-${slug}-${date}.${ext}`;
}

function longDate(d: Date): string {
  return d.toLocaleDateString("en-GB", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });
}

