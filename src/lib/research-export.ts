export interface Inline {
  text: string;
  bold?: boolean;
  italic?: boolean;
  code?: boolean;
  link?: string;
}

export type Block =
  | { type: "heading"; level: number; inlines: Inline[] }
  | { type: "paragraph"; inlines: Inline[] }
  | { type: "list"; ordered: boolean; items: Inline[][] }
  | { type: "table"; header: string[]; rows: string[][] }
  | { type: "quote"; inlines: Inline[] }
  | { type: "code"; text: string }
  | { type: "rule" };

function decodeEntities(s: string): string {
  return s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

function inlines(tokens: Token[] | undefined, style: Omit<Inline, "text"> = {}): Inline[] {
  const out: Inline[] = [];
  for (const t of tokens ?? []) {
    switch (t.type) {
      case "strong":
        out.push(...inlines((t as Tokens.Strong).tokens, { ...style, bold: true }));
        break;
      case "em":
        out.push(...inlines((t as Tokens.Em).tokens, { ...style, italic: true }));
        break;
      case "codespan":
        out.push({ ...style, code: true, text: decodeEntities((t as Tokens.Codespan).text) });
        break;
      case "link":
        out.push(...inlines((t as Tokens.Link).tokens, { ...style, link: (t as Tokens.Link).href }));
        break;
      case "br":
        out.push({ ...style, text: "\n" });
        break;
      case "text": {
        const tt = t as Tokens.Text;
        if (tt.tokens?.length) out.push(...inlines(tt.tokens, style));
        else out.push({ ...style, text: decodeEntities(tt.text) });
        break;
      }
      case "escape":
        out.push({ ...style, text: decodeEntities((t as Tokens.Escape).text) });
        break;
      default:
        if ("text" in t && typeof (t as { text?: unknown }).text === "string") {
          out.push({ ...style, text: decodeEntities((t as { text: string }).text) });
        }
    }
  }
  return out;
}

function plain(tokens: Token[] | undefined): string {
  return inlines(tokens)
    .map((i) => i.text)
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}

export function markdownBlocks(md: string): Block[] {
  const blocks: Block[] = [];
  const walk = (tokens: Token[]) => {
    for (const t of tokens) {
      switch (t.type) {
        case "heading":
          blocks.push({ type: "heading", level: (t as Tokens.Heading).depth, inlines: inlines((t as Tokens.Heading).tokens) });
          break;
        case "paragraph":
          blocks.push({ type: "paragraph", inlines: inlines((t as Tokens.Paragraph).tokens) });
          break;
        case "list": {
          const l = t as Tokens.List;
          const items: Inline[][] = [];
          for (const item of l.items) {
            const parts: Inline[] = [];
            for (const sub of item.tokens) {
              if (sub.type === "list") {
                // Nested list: flattened into the parent item.
                for (const nested of (sub as Tokens.List).items) {
                  parts.push({ text: "\n– " }, ...inlines(nested.tokens.flatMap((x) => ("tokens" in x && x.tokens ? x.tokens : [x])) as Token[]));
                }
              } else if ("tokens" in sub && sub.tokens) {
                parts.push(...inlines(sub.tokens as Token[]));
              } else if ("text" in sub) {
                parts.push({ text: decodeEntities(String((sub as { text: string }).text)) });
              }
            }
            items.push(parts);
          }
          blocks.push({ type: "list", ordered: l.ordered, items });
          break;
        }
        case "table": {
          const tb = t as Tokens.Table;
          blocks.push({
            type: "table",
            header: tb.header.map((c) => plain(c.tokens)),
            rows: tb.rows.map((r) => r.map((c) => plain(c.tokens))),
          });
          break;
        }
        case "blockquote":
          blocks.push({ type: "quote", inlines: inlines(((t as Tokens.Blockquote).tokens ?? []).flatMap((x) => ("tokens" in x && x.tokens ? (x.tokens as Token[]) : []))) });
          break;
        case "code":
          blocks.push({ type: "code", text: (t as Tokens.Code).text });
          break;
        case "hr":
          blocks.push({ type: "rule" });
          break;
        default:
          break;
      }
    }
  };
  walk(marked.lexer(md ?? ""));
  return blocks;
}

/** Plain Markdown edition of the report (for "Copy" and the .md export). */
export function reportMarkdown(report: ResearchReport): string {
  const lines: string[] = [
    `# ${report.title}`,
    "",
    `*${report.journal.name}${report.journal.issn ? ` · ISSN ${report.journal.issn}` : ""} · AI Research Assistant · ${longDate(report.generatedAt)}*`,
    "",
  ];
  report.items.forEach((item, i) => {
    if (report.items.length > 1) lines.push(`## Question ${i + 1}`, "");
    lines.push(`**Question:** ${item.question}`, "", item.answer, "");
    if (item.citations.length) {
      lines.push("**Evidence cited**", "");
      for (const c of item.citations) {
        const s = item.sources.find((x) => x.id === c.sourceId);
        lines.push(`[${c.n}] ${s ? `${s.title}. ` : ""}${c.kind === "record" ? "Article record: " : ""}“${c.text.replace(/\s+/g, " ").slice(0, 400)}”`);
      }
      lines.push("");
    }
    if (item.warnings?.length) lines.push(...item.warnings.map((w) => `> ${w}`), "");
  });
  const refs = consolidatedReferences(report);
  if (refs.length) lines.push("## References", "", ...refs.map((r) => r.reference), "");
  lines.push("---", "", REPORT_NOTE, "");
  return lines.join("\n");
}

