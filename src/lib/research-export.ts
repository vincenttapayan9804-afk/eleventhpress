// Module state so the run helpers pick up a whitelabel tenant's colours;
// set and reset synchronously inside buildResearchDocx (no await between).
let DOCX_PURPLE = "4C1D95";
let DOCX_GOLD = "8A6A28";
const DOCX_MUTED = "6B6478";
const DOCX_TINT = "F7F4FC";

function docxRuns(items: Inline[], base: { size?: number; color?: string } = {}): ParagraphChild[] {
  const out: ParagraphChild[] = [];
  for (const it of items) {
    for (const part of it.text.split(/(\[\d+\])/)) {
      if (!part) continue;
      const cite = /^\[\d+\]$/.test(part);
      const run = new TextRun({
        text: part,
        bold: it.bold || cite,
        italics: it.italic,
        font: it.code ? "Consolas" : undefined,
        size: cite ? (base.size ?? 22) - 4 : base.size,
        color: cite || it.link ? DOCX_PURPLE : base.color,
        ...(cite ? { superScript: false } : {}),
      });
      out.push(it.link ? new ExternalHyperlink({ link: it.link, children: [run] }) : run);
    }
  }
  return out;
}

function docxBlocks(blocks: Block[]): (Paragraph | Table)[] {
  const out: (Paragraph | Table)[] = [];
  for (const b of blocks) {
    switch (b.type) {
      case "heading":
        out.push(new Paragraph({ heading: HeadingLevel.HEADING_3, children: docxRuns(b.inlines) }));
        break;
      case "paragraph":
        out.push(new Paragraph({ children: docxRuns(b.inlines), spacing: { after: 140 } }));
        break;
      case "list":
        for (const item of b.items) {
          out.push(
            new Paragraph({
              children: docxRuns(item),
              ...(b.ordered ? { numbering: { reference: "answer-numbers", level: 0 } } : { bullet: { level: 0 } }),
              spacing: { after: 80 },
            })
          );
        }
        break;
      case "table": {
        const cols = Math.max(b.header.length, ...b.rows.map((r) => r.length));
        const cell = (text: string, header: boolean) =>
          new TableCell({
            children: [new Paragraph({ children: [new TextRun({ text, bold: header, size: 18, color: header ? "FFFFFF" : undefined })] })],
            shading: header ? { type: ShadingType.CLEAR, color: "auto", fill: "2A1458" } : undefined,
            margins: { top: 60, bottom: 60, left: 80, right: 80 },
          });
        out.push(
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: [
              new TableRow({ tableHeader: true, children: Array.from({ length: cols }, (_, i) => cell(b.header[i] ?? "", true)) }),
              ...b.rows.map((r) => new TableRow({ children: Array.from({ length: cols }, (_, i) => cell(r[i] ?? "", false)) })),
            ],
          })
        );
        out.push(new Paragraph({ text: "" }));
        break;
      }
      case "quote":
        out.push(
          new Paragraph({
            children: docxRuns(b.inlines, { color: DOCX_MUTED }),
            indent: { left: 360 },
            border: { left: { style: BorderStyle.SINGLE, size: 12, color: "C9A55C", space: 8 } },
          })
        );
        break;
      case "code":
        out.push(new Paragraph({ children: [new TextRun({ text: b.text, font: "Consolas", size: 18 })] }));
        break;
      case "rule":
        out.push(new Paragraph({ border: { bottom: { style: BorderStyle.SINGLE, size: 4, color: "E4DFEE", space: 4 } } }));
        break;
    }
  }
  return out;
}

export async function buildResearchDocx(report: ResearchReport): Promise<Buffer> {
  const pal = paletteFor(report.journal);
  DOCX_PURPLE = pal.purple.replace("#", "").toUpperCase();
  DOCX_GOLD = pal.goldDeep.replace("#", "").toUpperCase();
  try {
    return await Packer.toBuffer(researchDocxDocument(report));
  } finally {
    DOCX_PURPLE = "4C1D95";
    DOCX_GOLD = "8A6A28";
  }
}

function researchDocxDocument(report: ResearchReport): Document {
  const j = report.journal;
  const children: (Paragraph | Table)[] = [
    new Paragraph({
      children: [new TextRun({ text: j.name.toUpperCase(), bold: true, color: DOCX_GOLD, size: 18, characterSpacing: 40 })],
    }),
    new Paragraph({
      children: [
        new TextRun({
          text: [j.issn ? `ISSN ${j.issn}` : null, j.eissn ? `e-ISSN ${j.eissn}` : null, j.publisher !== j.name ? j.publisher : null, report.siteUrl.replace(/^https?:\/\//, "")].filter(Boolean).join("  ·  "),
          color: DOCX_MUTED,
          size: 17,
        }),
      ],
      spacing: { after: 240 },
    }),
    new Paragraph({
      children: [
        new TextRun({
          text: report.scope === "conversation" ? "AI RESEARCH ASSISTANT · CONVERSATION REPORT" : "AI RESEARCH ASSISTANT · RESEARCH BRIEF",
          bold: true,
          color: DOCX_PURPLE,
          size: 16,
          characterSpacing: 30,
        }),
      ],
    }),
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun({ text: report.title })] }),
    new Paragraph({
      children: [
        new TextRun({
          text: `Generated ${longDate(report.generatedAt)} · ${report.items.length} question${report.items.length === 1 ? "" : "s"}`,
          color: DOCX_MUTED,
          size: 18,
        }),
      ],
      spacing: { after: 240 },
    }),
    new Paragraph({
      children: [new TextRun({ text: "About this report. ", bold: true, color: DOCX_PURPLE, size: 18 }), new TextRun({ text: REPORT_NOTE, size: 18 })],
      shading: { type: ShadingType.CLEAR, color: "auto", fill: DOCX_TINT },
      border: { left: { style: BorderStyle.SINGLE, size: 18, color: "C9A55C", space: 8 } },
      spacing: { after: 320 },
    }),
  ];

  report.items.forEach((item, idx) => {
    children.push(
      new Paragraph({
        heading: HeadingLevel.HEADING_1,
        children: [new TextRun({ text: report.items.length > 1 ? `Question ${idx + 1}` : "Question" })],
      }),
      new Paragraph({
        children: [new TextRun({ text: item.question, italics: true, size: 24 })],
        shading: { type: ShadingType.CLEAR, color: "auto", fill: DOCX_TINT },
        border: { left: { style: BorderStyle.SINGLE, size: 18, color: DOCX_PURPLE, space: 8 } },
        spacing: { after: 200 },
      }),
      new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text: "Answer" })] }),
      ...docxBlocks(markdownBlocks(item.answer))
    );
    if (item.evidenceStatus) {
      children.push(
        new Paragraph({
          children: [
            new TextRun({ text: STATUS_LABEL[item.evidenceStatus], bold: true, size: 17, color: item.evidenceStatus === "verified" ? "1F6F4A" : DOCX_GOLD }),
            ...(item.warnings ?? []).map((w) => new TextRun({ text: w, size: 17, break: 1 })),
          ],
          spacing: { before: 120, after: 200 },
        })
      );
    }
    if (item.citations.length) {
      children.push(new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text: "Evidence cited" })] }));
      for (const c of item.citations) {
        const s = item.sources.find((x) => x.id === c.sourceId);
        const excerpt = c.text.replace(/\s+/g, " ").trim();
        children.push(
          new Paragraph({
            indent: { left: 440, hanging: 440 },
            spacing: { after: 120 },
            children: [
              new TextRun({ text: `[${c.n}]\t`, bold: true, color: DOCX_PURPLE, size: 18 }),
              ...(s ? [new ExternalHyperlink({ link: s.url, children: [new TextRun({ text: s.title, bold: true, size: 18 })] }), new TextRun({ text: ". ", size: 18 })] : []),
              new TextRun({
                text: `${c.kind === "record" ? "Article record: " : ""}“${excerpt.length > 420 ? `${excerpt.slice(0, 420)}…` : excerpt}”`,
                size: 18,
                color: DOCX_MUTED,
              }),
            ],
          })
        );
      }
    }
  });

  const refs = consolidatedReferences(report);
  if (refs.length) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun({ text: "References" })] }));
    for (const r of refs) {
      children.push(
        new Paragraph({
          indent: { left: 720, hanging: 720 },
          spacing: { after: 140 },
          children: [new TextRun({ text: r.reference })],
        })
      );
    }
  }

  const document = new Document({
    creator: `${j.name} — AI Research Assistant`,
    title: report.title,
    description: "Research report generated by the journal's AI Research Assistant",
    styles: {
      default: { document: { run: { font: "Cambria", size: 22, color: "2E2742" }, paragraph: { spacing: { line: 300, lineRule: LineRuleType.AUTO } } } },
      paragraphStyles: [
        { id: "Title", name: "Title", basedOn: "Normal", next: "Normal", run: { font: "Cambria", size: 44, bold: true, color: "2A1458" }, paragraph: { spacing: { before: 160, after: 80, line: 264, lineRule: LineRuleType.AUTO } } },
        { id: "Heading1", name: "Heading 1", basedOn: "Normal", next: "Normal", quickFormat: true, run: { font: "Cambria", size: 30, bold: true, color: DOCX_PURPLE }, paragraph: { keepNext: true, spacing: { before: 360, after: 140 } } },
        { id: "Heading2", name: "Heading 2", basedOn: "Normal", next: "Normal", quickFormat: true, run: { font: "Calibri", size: 18, bold: true, color: DOCX_GOLD, allCaps: true, characterSpacing: 30 }, paragraph: { keepNext: true, spacing: { before: 240, after: 100 } } },
        { id: "Heading3", name: "Heading 3", basedOn: "Normal", next: "Normal", quickFormat: true, run: { font: "Cambria", size: 24, bold: true, color: DOCX_PURPLE }, paragraph: { keepNext: true, spacing: { before: 200, after: 80 } } },
      ],
    },
    numbering: {
      config: [
        {
          reference: "answer-numbers",
          levels: [{ level: 0, format: LevelFormat.DECIMAL, text: "%1.", alignment: AlignmentType.START, style: { paragraph: { indent: { left: 440, hanging: 300 } } } }],
        },
      ],
    },
    sections: [
      {
        properties: { page: { margin: { top: 1200, bottom: 1200, left: 1200, right: 1200 } } },
        headers: {
          default: new Header({
            children: [
              new Paragraph({
                alignment: AlignmentType.RIGHT,
                children: [new TextRun({ text: `${j.name} · AI Research Assistant`, size: 15, color: DOCX_MUTED })],
              }),
            ],
          }),
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun({ text: "AI-generated from the journal's published articles. Verify against the original publications.  ·  Page ", size: 15, color: DOCX_MUTED }),
                  new TextRun({ children: [PageNumber.CURRENT], size: 15, color: DOCX_MUTED }),
                  new TextRun({ text: " of ", size: 15, color: DOCX_MUTED }),
                  new TextRun({ children: [PageNumber.TOTAL_PAGES], size: 15, color: DOCX_MUTED }),
                ],
              }),
              ...(j.whitelabel
                ? [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: POWERED_BY_CREDIT, size: 14, color: DOCX_MUTED })] })]
                : []),
            ],
          }),
        },
        children,
      },
    ],
  });
  return document;
}
